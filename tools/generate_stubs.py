"""Generate IDE signatures without changing Cython's runtime callables.

Run with Cython 0.29.37 (the release source generator), e.g.:
    uv run --no-project --with Cython==0.29.37 python tools/generate_stubs.py
Add --check to detect stale stubs without writing them.

Use Cython's parser rather than parsing its C-style docstring signatures, which
JetBrains can mistake for names like ``ImGuiWindowFlags_flags``. These are
signature stubs, not a complete type model: Any deliberately preserves the
binding's existing conversions, callbacks and polymorphic return values.
"""
import argparse
import ast
from pathlib import Path

from Cython.Compiler.TreeFragment import parse_from_strings

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "meltygui_imgui"
HEADER = '''# Generated by tools/generate_stubs.py; do not edit.
# Parameter names and optionality come from the Cython source.
import sys
from typing import Any, NamedTuple, Self
from contextlib import AbstractContextManager

'''

# Preserve completion through the most common object accessors. Other return
# values remain Any until their types can be described without narrowing the API.
RETURNS = {
    "get_io": "_IO",
    "get_style": "GuiStyle",
    "get_window_draw_list": "_DrawList",
    "get_overlay_draw_list": "_DrawList",
    "get_background_draw_list": "_DrawList",
    "get_foreground_draw_list": "_DrawList",
    "get_main_viewport": "_ImGuiViewport",
    "_IO.fonts": "_FontAtlas",
}


def statements(node):
    if type(node).__name__ == "StatListNode":
        for child in node.stats:
            yield from statements(child)
    else:
        yield node


def expression_name(node):
    if type(node).__name__ == "NameNode":
        return node.name
    if type(node).__name__ == "AttributeNode":
        return expression_name(node.obj) + "." + node.attribute
    return ""


def function(node, owner="", name=None):
    cpdef = type(node).__name__ == "CFuncDefNode"
    name = name or (node.declarator.base.name if cpdef else node.name)
    args = node.declarator.args if cpdef else node.args
    parameters = []
    star = getattr(node, "star_arg", None)
    inserted_star = False
    for arg in args:
        if arg.kw_only and not inserted_star:
            parameters.append("*" + star.name + ": Any" if star else "*")
            inserted_star = True
        # Untyped cpdef arguments are parsed as a base type with an empty
        # declarator until Cython's later analysis pass.
        parameter = arg.declarator.name or arg.base_type.name
        if parameter != "self":
            parameter += ": Any"
        if arg.default is not None:
            parameter += " = ..."
        parameters.append(parameter)
    if star and not inserted_star:
        parameters.append("*" + star.name + ": Any")
    if getattr(node, "starstar_arg", None):
        parameters.append("**" + node.starstar_arg.name + ": Any")

    decorators = [expression_name(d.decorator) for d in (getattr(node, "decorators", None) or [])]
    result = RETURNS.get(f"{owner}.{name}" if owner else name, "Any")
    if name == "__init__" or any(d.endswith(".setter") for d in decorators):
        result = "None"
    elif name == "__enter__":
        result = "Self"
    elif "contextmanager" in decorators:
        result = "AbstractContextManager[Any]"
    # These wrappers construct the context-manager result directly. Keep its
    # properties visible while retaining tuple unpacking/indexing via Any.
    for statement in statements(node.body):
        value = getattr(statement, "value", None)
        if type(statement).__name__ == "ReturnStatNode" and value is not None:
            callee = expression_name(getattr(value, "function", None))
            if callee.startswith("_BeginEnd") and callee.endswith(".__new__"):
                result = callee.split(".")[0]
    lines = ["@" + d for d in decorators if d in ("property", "staticmethod", "classmethod") or d.endswith(".setter")]
    signature = f"def {name}({', '.join(parameters)}) -> {result}: ..."
    # Release builds use Cython 0.29 on Python 3.11/3.12 and Cython 3 on 3.13.
    # Only the former defaults to METH_O for a single required argument. Do not
    # silently promise keyword support that the older runtime doesn't provide.
    ordinary_args = args[1:] if owner and "staticmethod" not in decorators else args
    if (not name.startswith("__") and not decorators
            and len(ordinary_args) == 1 and ordinary_args[0].default is None
            and not ordinary_args[0].kw_only and not star and not getattr(node, "starstar_arg", None)):
        return ["if sys.version_info >= (3, 13):", "    " + signature,
                "else:", f"    def {name}({', '.join(parameters)}, /) -> {result}: ..."]
    if "contextmanager" in decorators and len(ordinary_args) == 1 and ordinary_args[0].default is None:
        return ["if sys.version_info >= (3, 13):", "    " + signature,
                "else:", f"    def {name}({', '.join(parameters)}, /) -> {result}: ..."]
    lines.append(signature)
    return lines


def generate(module):
    path = PACKAGE / f"{module}.pyx"
    # Parsing from strings needs includes expanded; this is the sole shared
    # Python-visible include in these two extensions.
    source = path.read_text().replace('include "meltygui_imgui/common.pyx"', (PACKAGE / "common.pyx").read_text())
    tree = parse_from_strings(str(path), source)
    nodes = list(statements(tree.body))
    functions = {n.name for n in nodes if type(n).__name__ == "DefNode"}
    functions.update(n.declarator.base.name for n in nodes if type(n).__name__ == "CFuncDefNode" and n.overridable)
    lines = []
    for node in nodes:
        kind = type(node).__name__
        if kind == "DefNode" or (kind == "CFuncDefNode" and node.overridable):
            lines.extend(function(node))
        elif kind == "CClassDefNode":
            members = list(statements(node.body))
            has_init = any(getattr(m, "name", None) == "__init__" for m in members)
            setters = {m.name: m for m in members if type(m).__name__ == "DefNode"
                       and any(expression_name(d.decorator).endswith(".setter") for d in (m.decorators or []))}
            body = []
            for member in members:
                if type(member).__name__ == "DefNode":
                    if member in setters.values():
                        continue
                    if member.name == "__dealloc__":
                        continue
                    if member.name == "__cinit__":
                        if not has_init:
                            body.extend(function(member, node.class_name, "__init__"))
                    else:
                        body.extend(function(member, node.class_name))
                        if member.name in setters:
                            body.extend(function(setters[member.name], node.class_name))
                elif type(member).__name__ == "CVarDefNode" and member.visibility in ("public", "readonly"):
                    for declarator in member.declarators:
                        if member.visibility == "readonly":
                            body.extend(["@property", f"def {declarator.name}(self) -> Any: ..."])
                        else:
                            body.append(f"{declarator.name}: Any")
            lines.append(f"class {node.class_name}:")
            lines.extend("    " + line for line in (body or ["..."]))
        elif kind == "SingleAssignmentNode" and type(node.lhs).__name__ == "NameNode":
            name = node.lhs.name
            if name in ("Vec2", "Vec4"):
                fields = "xy" if name == "Vec2" else "xyzw"
                lines.append(f"class {name}(NamedTuple):")
                lines.extend(f"    {field}: Any" for field in fields)
            elif name == "ImGuiError":
                lines.append("class ImGuiError(Exception): ...")
            elif not name.startswith("_"):
                rhs = expression_name(node.rhs)
                if rhs in functions:
                    lines.append(f"{name} = {rhs}")
                else:
                    lines.append(f"{name}: Any")
        if lines and lines[-1]:
            lines.append("")
    output = HEADER + "\n".join(lines).strip() + "\n"
    ast.parse(output)  # Never write syntactically invalid Python stubs.
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for module in ("core", "internal"):
        path = PACKAGE / f"{module}.pyi"
        output = generate(module)
        if args.check:
            if not path.exists() or path.read_text() != output:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(output)
            print(f"Generated {path.relative_to(ROOT)}")
    if stale:
        parser.exit(1, "Stale stubs: " + ", ".join(stale) + "\nRun tools/generate_stubs.py\n")


if __name__ == "__main__":
    main()
